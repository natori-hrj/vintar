"""Generate the IDNA2008, casing and decimal data used by the Go casefile reader.

Run from the locked v0.6.0 Python environment and pass the output path.
The generated file is used by Go; Python is not needed to build or run it.
"""

import sys
import unicodedata
from itertools import groupby
from pathlib import Path

import idna
from idna import idnadata
from idna.intranges import intranges_contain


def property_bits(value: int) -> int:
    ch = chr(value)
    direction = unicodedata.bidirectional(ch)
    if not direction:
        return 0

    # Probe CPython's Final_Sigma rule for the effective Cased and
    # Case_Ignorable sets, including characters which have both properties.
    sigma = "A\u03a3" + ch
    cased = (sigma + ".").lower()[1] == "\u03c3"
    ignorable = not cased and (sigma + "A").lower()[1] == "\u03c3"
    text = not unicodedata.category(ch).startswith("C")
    result = (int(cased) << 5) | (int(ignorable) << 6) | (int(text) << 17)
    for kind, name in enumerate(("PVALID", "CONTEXTJ", "CONTEXTO")):
        if intranges_contain(value, idnadata.codepoint_classes[name]):
            result |= 1 << kind
            break
    else:
        return result

    result |= int(unicodedata.category(ch).startswith("M")) << 3
    result |= int(unicodedata.combining(ch) == 9) << 4  # Virama
    result |= int(intranges_contain(value, idnadata.scripts["Greek"])) << 7
    result |= int(intranges_contain(value, idnadata.scripts["Hebrew"])) << 8
    japanese = any(
        intranges_contain(value, idnadata.scripts[name])
        for name in ("Han", "Hiragana", "Katakana")
    )
    result |= int(japanese) << 9
    # Corresponds to the Go host direction and joining constants.
    directions = ("", "L", "R", "AL", "AN", "EN", "ES", "CS", "ET", "ON", "BN", "NSM")
    result |= directions.index(direction) << 10
    for kind, name in enumerate("LRDT", start=1):
        if intranges_contain(value, idnadata.joining_types[name]):
            result |= kind << 14
            break
    return result


def emit_ranges(output, name: str, values) -> None:
    output.write(f"var {name} = [...]hostRange{{\n")
    for value, indices in groupby(enumerate(values), key=lambda entry: entry[1]):
        if not value:
            continue
        first = last = None
        for index, _ in indices:
            if first is None:
                first = index
            last = index
        output.write(f"\t{{0x{first:X}, 0x{last:X}, {value}}},\n")
    output.write("}\n\n")


def main() -> None:
    if (idna.__version__, idnadata.__version__, unicodedata.unidata_version) != (
        "3.20",
        "18.0.0",
        "15.1.0",
    ):
        raise SystemExit("Use the locked v0.6.0 reference environment.")

    with Path(sys.argv[1]).open("w", encoding="utf-8") as output:
        output.write(
            "// Code generated by scripts/generate_casefile_hostname_tables.py; DO NOT EDIT.\n"
            "// Sources: idna 3.20 IDNA2008 data and CPython Unicode 15.1. See hostname_tables.LICENSE.\n\n"
        )
        output.write("package casefile\n\n")
        codepoints = range(sys.maxunicode + 1)
        emit_ranges(output, "hostProperties", map(property_bits, codepoints))
        lowercase = [chr(cp).lower() for cp in codepoints]
        emit_ranges(
            output,
            "hostLowerDeltas",
            (ord(s) - cp if len(s) == 1 else 0 for cp, s in enumerate(lowercase)),
        )
        output.write("var hostLowerExpansions = map[rune]string{\n")
        for cp, s in enumerate(lowercase):
            if len(s) != 1:
                literal = "".join(f"\\U{ord(ch):08x}" for ch in s)
                output.write(f'\t0x{cp:X}: "{literal}",\n')
        output.write("}\n")
        output.write("\n// First code point of each Unicode decimal digit block.\n")
        output.write("var storedDecimalStarts = [...]rune{\n")
        for cp in codepoints:
            if unicodedata.decimal(chr(cp), -1) == 0:
                output.write(f"\t0x{cp:X},\n")
        output.write("}\n")


if __name__ == "__main__":
    main()
